#!/bin/bash
# SPDX-License-Identifier: MIT
# M12/M13: GLSL -> SPIR-V for the meta shaders, then src/mali_meta_spv.h (committed; the driver embeds the SPIR-V, no file access at runtime).
set -e; cd "$(dirname "$0")"
H=../src/mali_meta_spv.h
echo "/* SPDX-License-Identifier: MIT. GENERATED by shader/gen-meta-spv.sh from shader/meta_*.comp, do not edit. */" > $H
for s in meta_copy meta_blit meta_qcopy; do
   glslangValidator -V --target-env vulkan1.1 $s.comp -o $s.comp.spv >/dev/null
   spirv-val $s.comp.spv
   echo "static const uint32_t ${s}_spv[] = {" >> $H
   od -An -v -tx4 -w16 $s.comp.spv | sed -E 's/ ([0-9a-f]{8})/0x\1,/g' >> $H
   echo "};" >> $H
done
# R4: graphics preload shaders (colour loadOp LOAD) -> src/mali_preload_spv.h
H=../src/mali_preload_spv.h
echo "/* SPDX-License-Identifier: MIT. GENERATED by shader/gen-meta-spv.sh from shader/preload.{vert,frag}, do not edit. */" > $H
for s in preload.vert preload.frag; do
   glslangValidator -V --target-env vulkan1.1 $s -o $s.spv >/dev/null
   spirv-val $s.spv
   n=$(echo $s | tr . _)
   echo "static const uint32_t ${n}_spv[] = {" >> $H
   od -An -v -tx4 -w16 $s.spv | sed -E 's/ ([0-9a-f]{8})/0x\1,/g' >> $H
   echo "};" >> $H
done
# integer render targets: preload.frag with an integer-typed colour output (uvec4 / ivec4)
for v in uint:OUT_U sint:OUT_S; do
   n=preload_${v%%:*}_frag
   glslangValidator -V --target-env vulkan1.1 -D${v#*:} preload.frag -o $n.spv >/dev/null
   spirv-val $n.spv
   echo "static const uint32_t ${n}_spv[] = {" >> $H
   od -An -v -tx4 -w16 $n.spv | sed -E 's/ ([0-9a-f]{8})/0x\1,/g' >> $H
   echo "};" >> $H
done
# multisampled loadOp LOAD: preload.frag with per-sample reads (gl_SampleID), sample shading
n=preload_msaa_frag
glslangValidator -V --target-env vulkan1.1 -DOUT_SAMPLE preload.frag -o $n.spv >/dev/null
spirv-val $n.spv
echo "static const uint32_t ${n}_spv[] = {" >> $H
od -An -v -tx4 -w16 $n.spv | sed -E 's# ([0-9a-f]{8})#0x\1,#g' >> $H
echo "};" >> $H
# depth/stencil loadOp LOAD: preload_zs.frag variants (Z, S, ZS)
for v in z:DO_Z s:DO_S zs:DO_Z:DO_S; do
   n=preload_${v%%:*}_frag; defs=""
   for d in $(echo ${v#*:} | tr : ' '); do defs="$defs -D$d"; done
   glslangValidator -V --target-env vulkan1.1 $defs preload_zs.frag -o $n.spv >/dev/null
   spirv-val $n.spv
   echo "static const uint32_t ${n}_spv[] = {" >> $H
   od -An -v -tx4 -w16 $n.spv | sed -E 's/ ([0-9a-f]{8})/0x\1,/g' >> $H
   echo "};" >> $H
done
